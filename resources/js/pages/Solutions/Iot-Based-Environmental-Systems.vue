      <script> 
        function toggleSection(sectionId) { 
          const section = document.getElementById(sectionId); 
          const hiddenCards = section.querySelectorAll('.hidden-card'); 
          const btnText = section.querySelector('.btn-text'); 
          const btnIcon = section.querySelector('.btn-icon'); 
           
          const choicesAreHidden = hiddenCards[0].classList.contains('hidden'); 
           
          hiddenCards.forEach(card => { 
            if (choicesAreHidden) { 
              card.classList.remove('hidden'); 
            } else { 
              card.classList.add('hidden'); 
            } 
          }); 
           
          if (choicesAreHidden) { 
            btnText.textContent = 'Show Less'; 
            if (btnIcon) btnIcon.classList.add('rotate-180'); 
          } else { 
            btnText.textContent = 'Show More'; 
            if (btnIcon) btnIcon.classList.remove('rotate-180'); 
          } 
        } 
      </script> 
      
